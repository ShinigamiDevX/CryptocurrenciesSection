import uuid
from datetime import datetime
from typing import Optional

from pydantic import BaseModel, Field


class Ransomware(BaseModel):
    companyName: Optional[str] = Field(default_factory=lambda: None) # Bussiness name
    companyLink: Optional[str] = Field(default_factory=lambda: None) # Business website
    victimAddress: Optional[str] = Field(default_factory=lambda: None) # Physical address of the affected bussiness 
    victimTLD: Optional[str] = Field(default_factory=lambda: None) # Top level domain of the affected bussiness
    url: str # Darkweb URL
    domainName: str = Field(default_factory=lambda: None) # Domain name 
    path: Optional[str] = Field(default_factory=lambda: None) # Path 
    urlSignature: uuid.UUID = Field(default_factory=lambda: None) # URL signature
    postSignature: str # Post signature, calculated from the post url
    network: str # Darknet network (e.g. Tor, I2P, Freenet, Clearnet)
    networkProtocol: str = Field(default_factory=lambda: None) # Network protocol (e.g. HTTP, HTTPS, FTP, SFTP, etc.)
    ransomwarePost: Optional[str] = Field(default_factory=lambda: None) # Ransomware post content
    ransomwareGroup: str # Ransomware group name (e.g. REvil, DarkSide, etc.)
    detectionDate: datetime # Date of detection in UTC 
    deadlineDate: Optional[datetime] = Field(default_factory=lambda: None) # Date of victim's data publication
    ingestionDate: Optional[datetime] = Field(default_factory=lambda: None) # Date of victim's data ingestion
    pageTitle: Optional[str] = Field(default_factory=lambda: None) # Page title
    html: str # HTML content of the page
    text: Optional[str] = Field(default_factory=lambda: None) # Text content of the page
    css: Optional[str] = Field(default_factory=lambda: None) # Possible detected CSS content
    js: Optional[str] = Field(default_factory=lambda: None) # Possible detected JS content
    country: Optional[str] = Field(default_factory=lambda: None) # Country of the affected bussiness
    ssdeep: Optional[str] = Field(default_factory=lambda: None) # SSDEEP hash of html content
    sha1sum: Optional[str] = Field(default_factory=lambda: None) # SHA1 hash of html content
    sha256sum: str # sha256 hash of html content
    etag: Optional[str] = Field(default_factory=lambda: None) # Etag generated by min.io
    bucketName: Optional[str] = Field(default_factory=lambda: None) # Minio bucket name
    minioCluster: Optional[str] = Field(default_factory=lambda: None) # Minio cluster name
    objectName: Optional[str] = Field(default_factory=lambda: None) # Minio object name


    class Config:
        json_encoders = {
            datetime: lambda dt: dt.strftime("%Y-%m-%d %H:%M:%S.%fZ"),
        }